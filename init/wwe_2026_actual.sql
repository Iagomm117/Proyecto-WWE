SET FOREIGN_KEY_CHECKS = 0;
SET NAMES utf8mb4;
SET CHARACTER SET utf8mb4;

DROP DATABASE IF EXISTS wwe_db;
CREATE DATABASE wwe_db
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE wwe_db;

CREATE TABLE marca (
    id_marca        INT             NOT NULL AUTO_INCREMENT,
    nome            VARCHAR(100)    NOT NULL,
    estado          ENUM('activa','inactiva') NOT NULL DEFAULT 'activa',
    min_loitadores  INT             NOT NULL DEFAULT 25,
    min_titulos     INT             NOT NULL DEFAULT 3,
    foto_url        VARCHAR(2000)    NULL COMMENT 'URL logo da marca',
    CONSTRAINT pk_marca PRIMARY KEY (id_marca),
    CONSTRAINT chk_marca_loitadores CHECK (min_loitadores >= 25),
    CONSTRAINT chk_marca_titulos    CHECK (min_titulos   >= 3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE equipo (
    id_equipo   INT             NOT NULL AUTO_INCREMENT,
    nome_equipo VARCHAR(100)    NOT NULL,
    id_marca    INT             NULL,
    descripcion TEXT            NULL,
    foto_url    VARCHAR(2000)    NULL COMMENT 'URL foto do equipo',
    CONSTRAINT pk_equipo PRIMARY KEY (id_equipo),
    CONSTRAINT fk_equipo_marca FOREIGN KEY (id_marca)
        REFERENCES marca(id_marca)
        ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE loitador (
    id_loitador         INT             NOT NULL AUTO_INCREMENT,
    nome                VARCHAR(100)    NOT NULL,
    estado              ENUM('activo','retirado','lesionado','indefinido') NOT NULL DEFAULT 'activo',
    entrada             TEXT            NULL,
    categoria_peso      VARCHAR(50)     NOT NULL DEFAULT 'Heavyweight',
    id_marca            INT             NULL,
    id_equipo           INT             NULL,
    foto_url            VARCHAR(2000)    NULL COMMENT 'URL foto oficial WWE',
    data_creacion       DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_modificacion   DATETIME        NULL ON UPDATE CURRENT_TIMESTAMP,
    veces_consultado    INT             Not NULL DEFAULT 0,
    CONSTRAINT pk_loitador PRIMARY KEY (id_loitador),
    CONSTRAINT fk_loitador_marca  FOREIGN KEY (id_marca)
        REFERENCES marca(id_marca)
        ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT fk_loitador_equipo FOREIGN KEY (id_equipo)
        REFERENCES equipo(id_equipo)
        ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE movemento (
    id_movemento    INT             NOT NULL AUTO_INCREMENT,
    nome_movemento  VARCHAR(100)    NOT NULL,
    descripcion     TEXT            NULL,
    CONSTRAINT pk_movemento PRIMARY KEY (id_movemento)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE loitador_movemento (
    id_loitador     INT NOT NULL,
    id_movemento    INT NOT NULL,
    CONSTRAINT pk_loitador_movemento PRIMARY KEY (id_loitador, id_movemento),
    CONSTRAINT fk_lm_loitador  FOREIGN KEY (id_loitador)
        REFERENCES loitador(id_loitador)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_lm_movemento FOREIGN KEY (id_movemento)
        REFERENCES movemento(id_movemento)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE titulo (
    id_titulo         INT             NOT NULL AUTO_INCREMENT,
    nome              VARCHAR(150)    NOT NULL,
    estado            ENUM('activo','vacante','inactivo') NOT NULL DEFAULT 'vacante',
    descripcion       TEXT            NULL,
    es_titulo_maximo  BOOLEAN         NOT NULL DEFAULT FALSE,
    data_vixencia     DATE            NOT NULL,
    id_marca          INT             NULL,
    foto_url          VARCHAR(2000)    NULL COMMENT 'URL foto do cinto',
    data_creacion       DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_modificacion DATETIME        NULL ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT pk_titulo PRIMARY KEY (id_titulo),
    CONSTRAINT fk_titulo_marca FOREIGN KEY (id_marca)
        REFERENCES marca(id_marca)
        ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE reinado_titulo (
    id_reinado   INT  NOT NULL AUTO_INCREMENT,
    id_titulo    INT  NOT NULL,
    id_loitador  INT  NOT NULL,
    data_inicio  DATE NOT NULL,
    data_fin     DATE NULL,
    dias_reinado INT  DEFAULT 0,
    PRIMARY KEY (id_reinado),
    FOREIGN KEY (id_titulo) REFERENCES titulo(id_titulo)
        ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_loitador) REFERENCES loitador(id_loitador)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CHECK (data_fin IS NULL OR data_fin > data_inicio)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE grupo_ppv (
    id_grupo_ppv            INT             NOT NULL AUTO_INCREMENT,
    nome_grupo              VARCHAR(100)    NOT NULL,
    descripcion_importancia TEXT            NULL,
    data_habitual           VARCHAR(50)     NULL,
    foto_url                VARCHAR(2000)    NULL,
    CONSTRAINT pk_grupo_ppv  PRIMARY KEY (id_grupo_ppv),
    CONSTRAINT uq_grupo_nome UNIQUE (nome_grupo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


CREATE TABLE ppv (
    id_ppv           INT             NOT NULL AUTO_INCREMENT,
    id_grupo_ppv     INT             NOT NULL,
    nome             VARCHAR(150)    NOT NULL,
    data_celebracion DATE            NOT NULL,
    estado           ENUM('realizado','pendente') NOT NULL DEFAULT 'pendente',
    localizacion     VARCHAR(200)    NULL,
    foto_url         VARCHAR(2000)    NULL,
    CONSTRAINT pk_ppv PRIMARY KEY (id_ppv),
    CONSTRAINT fk_ppv_grupo FOREIGN KEY (id_grupo_ppv)
        REFERENCES grupo_ppv(id_grupo_ppv)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE combate (
    id_combate          INT          NOT NULL AUTO_INCREMENT,
    id_ppv              INT          NOT NULL,
    id_titulo_en_xogo   INT          NULL,
    id_loitador_ganador INT          NULL,
    tipo_combate        VARCHAR(80)  NOT NULL DEFAULT 'Singles',
    orde_no_ppv         TINYINT      NULL,
    CONSTRAINT pk_combate PRIMARY KEY (id_combate),
    CONSTRAINT fk_combate_ppv     FOREIGN KEY (id_ppv)
        REFERENCES ppv(id_ppv)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_combate_titulo  FOREIGN KEY (id_titulo_en_xogo)
        REFERENCES titulo(id_titulo)
        ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT fk_combate_ganador FOREIGN KEY (id_loitador_ganador)
        REFERENCES loitador(id_loitador)
        ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE combate_loitador (
    id_combate  INT         NOT NULL,
    id_loitador INT         NOT NULL,
    bando       VARCHAR(50) NULL,
    CONSTRAINT pk_combate_loitador PRIMARY KEY (id_combate, id_loitador),
    CONSTRAINT fk_cl_combate  FOREIGN KEY (id_combate)
        REFERENCES combate(id_combate)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_cl_loitador FOREIGN KEY (id_loitador)
        REFERENCES loitador(id_loitador)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE usuario (
    id_usuario       INT          NOT NULL AUTO_INCREMENT,
    nome_usuario     VARCHAR(80)  NOT NULL,
    email            VARCHAR(150) NOT NULL,
    contrasinal_hash VARCHAR(255) NOT NULL,
    rol              ENUM('visitante','admin') NOT NULL DEFAULT 'visitante',
    data_rexistro    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_usuario        PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_nome   UNIQUE (nome_usuario),
    CONSTRAINT uq_usuario_email  UNIQUE (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


CREATE INDEX idx_loitador_marca   ON loitador(id_marca);
CREATE INDEX idx_loitador_equipo  ON loitador(id_equipo);
CREATE INDEX idx_titulo_marca     ON titulo(id_marca);
CREATE INDEX idx_reinado_titulo   ON reinado_titulo(id_titulo);
CREATE INDEX idx_reinado_loitador ON reinado_titulo(id_loitador);
CREATE INDEX idx_combate_ppv      ON combate(id_ppv);
CREATE INDEX idx_ppv_grupo        ON ppv(id_grupo_ppv);

DELIMITER $$
CREATE TRIGGER reinado_before_insert
BEFORE INSERT ON reinado_titulo
FOR EACH ROW
BEGIN
    SET NEW.dias_reinado = DATEDIFF(IFNULL(NEW.data_fin, CURDATE()), NEW.data_inicio);
END$$

CREATE TRIGGER reinado_before_update
BEFORE UPDATE ON reinado_titulo
FOR EACH ROW
BEGIN
    SET NEW.dias_reinado = DATEDIFF(IFNULL(NEW.data_fin, CURDATE()), NEW.data_inicio);
END$$

DELIMITER ;


